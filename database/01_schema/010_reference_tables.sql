CREATE TABLE Role (
  RoleCode VARCHAR(16) NOT NULL,
  RoleName VARCHAR(40) NOT NULL,
  PRIMARY KEY (RoleCode),
  CONSTRAINT ck_role_01 CHECK (RoleCode IN ('CUSTOMER','STAFF','ADMINISTRATOR')),
  CONSTRAINT ck_role_02 CHECK (CHAR_LENGTH(TRIM(RoleCode)) > 0 AND OCTET_LENGTH(RoleCode) = OCTET_LENGTH(TRIM(RoleCode))),
  CONSTRAINT ck_role_03 CHECK (CHAR_LENGTH(TRIM(RoleName)) > 0 AND OCTET_LENGTH(RoleName) = OCTET_LENGTH(TRIM(RoleName)))
) ENGINE=InnoDB;

CREATE TABLE OrderStatus (
  StatusCode VARCHAR(16) NOT NULL,
  StatusName VARCHAR(30) NOT NULL,
  PRIMARY KEY (StatusCode),
  CONSTRAINT ck_orderstatus_01 CHECK (StatusCode IN ('PENDING','READY_TO_SHIP','SHIPPED','CANCELLED')),
  CONSTRAINT ck_orderstatus_02 CHECK (CHAR_LENGTH(TRIM(StatusCode)) > 0 AND OCTET_LENGTH(StatusCode) = OCTET_LENGTH(TRIM(StatusCode))),
  CONSTRAINT ck_orderstatus_03 CHECK (CHAR_LENGTH(TRIM(StatusName)) > 0 AND OCTET_LENGTH(StatusName) = OCTET_LENGTH(TRIM(StatusName)))
) ENGINE=InnoDB;
