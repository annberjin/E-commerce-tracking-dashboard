CREATE TABLE OrderHeader (
  OrderID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  CustomerID INT UNSIGNED NOT NULL,
  SubmissionReference VARCHAR(64) NOT NULL,
  SubmittedAt DATETIME(6) NOT NULL,
  StatusCode VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  RecipientName VARCHAR(100) NOT NULL,
  StreetAddress VARCHAR(255) NOT NULL,
  City VARCHAR(100) NOT NULL,
  Region VARCHAR(100) NULL DEFAULT NULL,
  PostalCode VARCHAR(20) NOT NULL,
  Country VARCHAR(100) NOT NULL,
  CancellationReason VARCHAR(255) NULL DEFAULT NULL,
  CancelledAt DATETIME(6) NULL DEFAULT NULL,
  PRIMARY KEY (OrderID),
  UNIQUE KEY uq_orderheader_submissionreference (CustomerID, SubmissionReference),
  CONSTRAINT fk_orderheader_customerid FOREIGN KEY (CustomerID) REFERENCES Customer (CustomerID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_orderheader_statuscode FOREIGN KEY (StatusCode) REFERENCES OrderStatus (StatusCode) ON UPDATE RESTRICT ON DELETE RESTRICT,
  KEY ix_order_customer_time (CustomerID, SubmittedAt, OrderID),
  KEY ix_order_status_time (StatusCode, SubmittedAt, OrderID),
  CONSTRAINT ck_orderheader_01 CHECK ((StatusCode = 'CANCELLED' AND CancellationReason IS NOT NULL AND CHAR_LENGTH(TRIM(CancellationReason)) > 0 AND CancelledAt IS NOT NULL AND CancelledAt >= SubmittedAt) OR (StatusCode <> 'CANCELLED' AND CancellationReason IS NULL AND CancelledAt IS NULL)),
  CONSTRAINT ck_orderheader_02 CHECK (CHAR_LENGTH(TRIM(SubmissionReference)) > 0 AND OCTET_LENGTH(SubmissionReference) = OCTET_LENGTH(TRIM(SubmissionReference))),
  CONSTRAINT ck_orderheader_03 CHECK (CHAR_LENGTH(TRIM(StatusCode)) > 0 AND OCTET_LENGTH(StatusCode) = OCTET_LENGTH(TRIM(StatusCode))),
  CONSTRAINT ck_orderheader_04 CHECK (CHAR_LENGTH(TRIM(RecipientName)) > 0 AND OCTET_LENGTH(RecipientName) = OCTET_LENGTH(TRIM(RecipientName))),
  CONSTRAINT ck_orderheader_05 CHECK (CHAR_LENGTH(TRIM(StreetAddress)) > 0 AND OCTET_LENGTH(StreetAddress) = OCTET_LENGTH(TRIM(StreetAddress))),
  CONSTRAINT ck_orderheader_06 CHECK (CHAR_LENGTH(TRIM(City)) > 0 AND OCTET_LENGTH(City) = OCTET_LENGTH(TRIM(City))),
  CONSTRAINT ck_orderheader_07 CHECK (Region IS NULL OR (CHAR_LENGTH(TRIM(Region)) > 0 AND OCTET_LENGTH(Region) = OCTET_LENGTH(TRIM(Region)))),
  CONSTRAINT ck_orderheader_08 CHECK (CHAR_LENGTH(TRIM(PostalCode)) > 0 AND OCTET_LENGTH(PostalCode) = OCTET_LENGTH(TRIM(PostalCode))),
  CONSTRAINT ck_orderheader_09 CHECK (CHAR_LENGTH(TRIM(Country)) > 0 AND OCTET_LENGTH(Country) = OCTET_LENGTH(TRIM(Country))),
  CONSTRAINT ck_orderheader_10 CHECK (CancellationReason IS NULL OR (CHAR_LENGTH(TRIM(CancellationReason)) > 0 AND OCTET_LENGTH(CancellationReason) = OCTET_LENGTH(TRIM(CancellationReason))))
) ENGINE=InnoDB;

CREATE TABLE OrderLine (
  OrderID INT UNSIGNED NOT NULL,
  LineNumber INT UNSIGNED NOT NULL,
  ProductID INT UNSIGNED NOT NULL,
  Quantity INT NOT NULL,
  AcceptedUnitPrice DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (OrderID, LineNumber),
  UNIQUE KEY uq_orderline_productid (OrderID, ProductID),
  CONSTRAINT fk_orderline_orderid FOREIGN KEY (OrderID) REFERENCES OrderHeader (OrderID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_orderline_productid FOREIGN KEY (ProductID) REFERENCES Product (ProductID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT ck_orderline_01 CHECK (LineNumber > 0),
  CONSTRAINT ck_orderline_02 CHECK (Quantity > 0),
  CONSTRAINT ck_orderline_03 CHECK (AcceptedUnitPrice > 0)
) ENGINE=InnoDB;

CREATE TABLE Shipment (
  OrderID INT UNSIGNED NOT NULL,
  Carrier VARCHAR(80) NOT NULL,
  TrackingNumber VARCHAR(100) NOT NULL,
  DispatchedAt DATETIME(6) NOT NULL,
  PRIMARY KEY (OrderID),
  CONSTRAINT fk_shipment_orderid FOREIGN KEY (OrderID) REFERENCES OrderHeader (OrderID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  KEY ix_shipment_time (DispatchedAt, OrderID),
  CONSTRAINT ck_shipment_01 CHECK (CHAR_LENGTH(TRIM(Carrier)) > 0 AND OCTET_LENGTH(Carrier) = OCTET_LENGTH(TRIM(Carrier))),
  CONSTRAINT ck_shipment_02 CHECK (CHAR_LENGTH(TRIM(TrackingNumber)) > 0 AND OCTET_LENGTH(TrackingNumber) = OCTET_LENGTH(TRIM(TrackingNumber)))
) ENGINE=InnoDB;

CREATE TABLE AuditLog (
  AuditID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ActorAccountID INT UNSIGNED NOT NULL,
  EventType VARCHAR(40) NOT NULL,
  OccurredAt DATETIME(6) NOT NULL,
  EntityName VARCHAR(32) NOT NULL,
  RecordKey VARCHAR(100) NOT NULL,
  FieldName VARCHAR(64) NOT NULL,
  OldValue TEXT NULL DEFAULT NULL,
  NewValue TEXT NULL DEFAULT NULL,
  Reason VARCHAR(255) NULL DEFAULT NULL,
  ContextReference VARCHAR(64) NOT NULL,
  OrderID INT UNSIGNED NULL DEFAULT NULL,
  AdjustmentReference VARCHAR(64) NULL DEFAULT NULL,
  PRIMARY KEY (AuditID),
  UNIQUE KEY uq_auditlog_adjustmentreference (ActorAccountID, AdjustmentReference),
  CONSTRAINT fk_auditlog_actoraccountid FOREIGN KEY (ActorAccountID) REFERENCES UserAccount (AccountID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_auditlog_orderid FOREIGN KEY (OrderID) REFERENCES OrderHeader (OrderID) ON UPDATE RESTRICT ON DELETE RESTRICT,
  KEY ix_audit_order_time (OrderID, OccurredAt, AuditID),
  KEY ix_audit_record_time (EntityName, RecordKey, OccurredAt, AuditID),
  CONSTRAINT ck_auditlog_01 CHECK (EventType IN ('CREATE','UPDATE','ACTIVATE','DEACTIVATE','ORDER_ACCEPTED','ORDER_READY','ORDER_SHIPPED','ORDER_CANCELLED','STOCK_DEDUCTED','STOCK_RESTORED','STOCK_ADJUSTED','TRACKING_CORRECTED')),
  CONSTRAINT ck_auditlog_02 CHECK (EntityName IN ('UserAccount','Customer','Product','Inventory','OrderHeader','OrderLine','Shipment')),
  CONSTRAINT ck_auditlog_03 CHECK ((EventType = 'STOCK_ADJUSTED' AND AdjustmentReference IS NOT NULL) OR (EventType <> 'STOCK_ADJUSTED' AND AdjustmentReference IS NULL)),
  CONSTRAINT ck_auditlog_04 CHECK (EventType NOT IN ('STOCK_ADJUSTED','STOCK_RESTORED','ORDER_CANCELLED','TRACKING_CORRECTED') OR (Reason IS NOT NULL AND CHAR_LENGTH(TRIM(Reason)) > 0)),
  CONSTRAINT ck_auditlog_05 CHECK (CHAR_LENGTH(TRIM(EventType)) > 0 AND OCTET_LENGTH(EventType) = OCTET_LENGTH(TRIM(EventType))),
  CONSTRAINT ck_auditlog_06 CHECK (CHAR_LENGTH(TRIM(EntityName)) > 0 AND OCTET_LENGTH(EntityName) = OCTET_LENGTH(TRIM(EntityName))),
  CONSTRAINT ck_auditlog_07 CHECK (CHAR_LENGTH(TRIM(RecordKey)) > 0 AND OCTET_LENGTH(RecordKey) = OCTET_LENGTH(TRIM(RecordKey))),
  CONSTRAINT ck_auditlog_08 CHECK (CHAR_LENGTH(TRIM(FieldName)) > 0 AND OCTET_LENGTH(FieldName) = OCTET_LENGTH(TRIM(FieldName))),
  CONSTRAINT ck_auditlog_09 CHECK (Reason IS NULL OR (CHAR_LENGTH(TRIM(Reason)) > 0 AND OCTET_LENGTH(Reason) = OCTET_LENGTH(TRIM(Reason)))),
  CONSTRAINT ck_auditlog_10 CHECK (CHAR_LENGTH(TRIM(ContextReference)) > 0 AND OCTET_LENGTH(ContextReference) = OCTET_LENGTH(TRIM(ContextReference))),
  CONSTRAINT ck_auditlog_11 CHECK (AdjustmentReference IS NULL OR (CHAR_LENGTH(TRIM(AdjustmentReference)) > 0 AND OCTET_LENGTH(AdjustmentReference) = OCTET_LENGTH(TRIM(AdjustmentReference))))
) ENGINE=InnoDB;
